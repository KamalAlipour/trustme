type Widen<T> = T extends (...args: infer Args) => infer Result
  ? (...args: Args) => Widen<Result>
  : T extends string
    ? string
    : T extends readonly (infer Item)[]
      ? readonly Widen<Item>[]
      : T extends object
        ? { [Key in keyof T]: Widen<T[Key]> }
        : T;

